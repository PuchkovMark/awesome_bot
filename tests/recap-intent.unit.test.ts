import { expect, test } from 'vitest';
import { isRecapRequest } from '../src/core/chat-summaries/recap-intent';

test.each([
  'объясни фразу «что было вчера?»',
  'что значит выражение “что было вчера?”',
  'объясни фразу "что было вчера?"',
  'объясни фразу `что было вчера?`',
  'объясни фразу «Она сказала «привет». Что было вчера?»',
  'объясни фразу “Она сказала “привет”. Что было вчера?”',
  'объясни фразу "Что было\nвчера?"',
  'объясни эти строки\n> что было вчера?\n  > дай сводку\nэто вопрос?',
  'что«цитата»было вчера?',
  'дай`пример`сводку за вчера',
  'что было бы, если бы встреча отменилась?',
  'перескажи книгу',
])('«%s» остаётся обычной репликой', (text) => {
  expect(isRecapRequest(text)).toBe(false);
});

test.each([
  'Что было вчера?',
  'дай сводку за вчера. В чате это назвали «репетицией».',
  'дай сводку за вчера. «Перескажи книгу» — отдельная просьба.',
  '> О встрече\nДай сводку за вчера.',
])('«%s» содержит собственную просьбу о пересказе', (text) => {
  expect(isRecapRequest(text)).toBe(true);
});
