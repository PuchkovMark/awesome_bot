function unknownObjects(db: Database.Database) {
  return (
    db
      .prepare("SELECT name,type FROM sqlite_schema WHERE name NOT LIKE 'sqlite_autoindex%'")
      .all() as { name: string; type: string }[]
  ).filter((o) => !(o.type === 'table' ? tables : others).includes(o.name));
}
test('все таблицы, FTS, индексы и триггеры классифицированы; новая сущность требует расширить очистку', () => {
  const db = new Database(':memory:');
  try {
    migrate(db);
    expect(unknownObjects(db)).toEqual([]);
    db.exec('CREATE TABLE new_chat_data(chat_id TEXT,value TEXT)');
    expect(unknownObjects(db)).toEqual([{ name: 'new_chat_data', type: 'table' }]);
  } finally {
    db.close();
  }
});
